"""Seed a new coverage group without replacing restored crates or caching reports."""

from __future__ import annotations

import os
import subprocess
from pathlib import Path

import pytest
import yaml

ROOT = Path(__file__).resolve().parents[1]


def _steps():
    action = yaml.safe_load((ROOT / ".github/actions/prepare-rust-coverage/action.yml").read_text())
    return action["runs"]["steps"]


def test_seed_is_read_only_profile_bound_and_only_runs_on_a_complete_miss():
    steps = _steps()
    primary = next(step for step in steps if step.get("id") == "coverage-cache")
    probe = next(step for step in steps if step.get("id") == "restored-dependencies")
    seed = next(step for step in steps if step.get("name", "").startswith("Seed instrumented"))
    build = next(step for step in steps if step.get("name") == "Generate current-checkout Rust coverage")
    assert steps.index(primary) < steps.index(probe) < steps.index(seed) < steps.index(build)
    assert seed["uses"] == primary["uses"]
    assert seed["with"]["save-if"] == "false"
    assert seed["with"]["workspaces"] == primary["with"]["workspaces"] == "rust"
    assert seed["with"]["shared-key"] == primary["with"]["shared-key"].replace("v2-${{ inputs.partition }}-", "")
    assert primary["with"]["cache-on-failure"] is False
    assert seed["if"] == "steps.restored-dependencies.outputs.restored != 'true'"
    assert "if" not in probe  # Even an exact archive may contain no instrumented crates.
    assert primary["with"]["save-if"] == "${{ github.event_name == 'push' && github.ref == 'refs/heads/main' }}"
    # Reports/profiles are still discarded and regenerated by the actual producer.
    script = (ROOT / "scripts/ci/prepare_sonar_rust_coverage.sh").read_text()
    assert 'rm -f "$report"' in script
    assert "llvm-cov clean --workspace" in script
    assert "--retries 0 --no-fail-fast --no-report" in script


@pytest.mark.skipif(os.name == "nt", reason="Instrumented coverage executes on Linux Bash")
@pytest.mark.parametrize(
    "entry",
    [
        None,
        "debug/deps/libdependency.rlib",
        "llvm-cov-target/debug/deps/libdependency.rmeta",
        "llvm-cov-target/debug/deps/libdependency.rlib",
        "llvm-cov-target/CACHEDIR.TAG",
        "CACHEDIR.TAG",
    ],
)
def test_restore_probe_distinguishes_real_dependency_archives_from_empty_targets(tmp_path, entry):
    if entry is not None:
        path = tmp_path / "rust/target" / entry
        path.parent.mkdir(parents=True)
        path.write_bytes(b"fixture")
    probe = next(step for step in _steps() if step.get("id") == "restored-dependencies")
    output = tmp_path / "output"
    subprocess.run(
        ["bash", "-e", "-o", "pipefail", "-c", probe["run"]],
        cwd=tmp_path,
        env={**os.environ, "GITHUB_OUTPUT": str(output)},
        check=True,
        capture_output=True,
        timeout=5,
    )
    restored = entry is not None and entry.startswith("llvm-cov-target/") and entry.endswith((".rlib", ".rmeta"))
    assert output.read_text() == ("restored=true\n" if restored else "restored=false\n")
