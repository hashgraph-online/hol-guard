import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
const history = fs.readFileSync(path.join(process.cwd(), "src/protection-center/protection-settings-history.tsx"), "utf8");
const policy = fs.readFileSync(path.join(process.cwd(), "src/extension-policy-panel.tsx"), "utf8");
const policyDraft = fs.readFileSync(path.join(process.cwd(), "src/use-extension-policy-draft.ts"), "utf8");
const notice = fs.readFileSync(path.join(process.cwd(), "src/protection-center/components/protection-authority-notice.tsx"), "utf8");
const workspace = fs.readFileSync(path.join(process.cwd(), "src/protection-center/protection-center-workspace.tsx"), "utf8");
assert.match(history, /Use this version as draft/);
assert.doesNotMatch(history, /applyExtensionMutation/);
assert.match(policyDraft, /historicalLocal/);
assert.match(policyDraft, /layer.kind === "local-admin"/);
assert.match(policy, /Review \{changeCount\} change/);
assert.match(notice, /recover-authority/);
assert.match(notice, /command controls enroll/);
assert.match(workspace, /authorityActionErrorMessage/);
assert.match(workspace, /authority_not_recoverable/);
assert.doesNotMatch(workspace, /error\.message \}\}\$\{recovery/, "authority errors must map to plain language");
