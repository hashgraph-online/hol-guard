def git(root: Path, *args: str) -> str:
    result = subprocess.run(["git", "-C", str(root), *args], check=True, capture_output=True, timeout=30)
    return result.stdout.decode().strip()


def _file_bytes(case: Workload, index: int, generation: int) -> bytes:
    number = generation % 2 if case.repeated else generation * case.files + index
    header = f"// generation {number:08d}\n"
    providers = provider_examples()
    if case.content == "providers":
        header += providers[index % len(providers)].text
    elif case.content == "catalog":
        header += "".join(example.text for example in providers)
    elif case.content == "dense":
        # Finding-heavy source, with matches spread throughout the entire file.
        # 170 matches/file remain well below the explicit 10,000-job budget.
        block = "".join(example.text for example in providers)
        spacing = "const value = 0;\n" * max(1, (case.size // 10 - len(block)) // 17)
        header += (block + spacing) * 10
    safe_line = "const value = 0;\n" if case.content != "safe" else "VALUE=ordinary\n"
    data = header.encode()
    if len(data) > case.size:
        raise ValueError("fixture size cannot contain the declared findings")
    return (data + safe_line.encode() * (case.size // len(safe_line) + 1))[: case.size]


def create_fixture(root: Path, case: Workload) -> dict[str, int]:
    root.mkdir()
    git(root, "init")
    git(root, "config", "user.name", "Guard Benchmark")
    git(root, "config", "user.email", "guard-benchmark@example.invalid")
    generations = 6 if case.workflow == "history" else 1
    for generation in range(generations):
        for index in range(case.files):
            suffix = ".json" if case.content == "safe" else ".ts"
            (root / f"config-{index:05d}{suffix}").write_bytes(_file_bytes(case, index, generation))
        git(root, "add", ".")
        if case.workflow == "history":
            git(root, "commit", "-m", f"generation {generation}")
    if case.unstaged_change:
        for path in root.glob("config-*"):
            path.write_text("const value = 0;\n")
    occurrences = case.files * (generations + 1 if case.workflow == "history" else 1)
    return {"files": case.files, "input_bytes": case.files * case.size, "file_occurrences": occurrences}
