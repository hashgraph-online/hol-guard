#[test]
fn endpoint_identity_matches_python_reference() {
    let mut mismatches = Vec::new();
    for (input, expected) in CASES {
        let actual = remote_mcp_endpoint_identity(input);
        if actual.as_deref() != *expected {
            mismatches.push(format!("{input:?}: rust={actual:?} python={expected:?}"));
        }
    }
    assert!(
        mismatches.is_empty(),
        "{} mismatches:\n{}",
        mismatches.len(),
        mismatches.join("\n")
    );
}
