            | "chdir"
            | "bye"
            | "limit"
            | "unlimit"
            | "rehash"
            | "functions"
            | "integer"
            | "float"
            | "noglob"
            | "nocorrect"
            | "repeat"
            | "foreach"
            | "end"
            | "coproc"
            | "autoload"
            | "bindkey"
            | "emulate"
