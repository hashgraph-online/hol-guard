//! Decimal digit forms `int()` accepts.
//!
//! Python's `int()` reads any Unicode decimal digit (general category `Nd`).
//! Each `Nd` block is ten consecutive code points starting at zero; this table
//! lists those starts as of Unicode 15.0.0 (the data the retired Python
//! handlers and the recorded vectors used).

const ZERO_DIGITS: [u32; 68] = [
    0x30, 0x660, 0x6F0, 0x7C0, 0x966, 0x9E6, 0xA66, 0xAE6, 0xB66, 0xBE6, 0xC66, 0xCE6, 0xD66,
    0xDE6, 0xE50, 0xED0, 0xF20, 0x1040, 0x1090, 0x17E0, 0x1810, 0x1946, 0x19D0, 0x1A80, 0x1A90,
    0x1B50, 0x1BB0, 0x1C40, 0x1C50, 0xA620, 0xA8D0, 0xA900, 0xA9D0, 0xA9F0, 0xAA50, 0xABF0, 0xFF10,
    0x104A0, 0x10D30, 0x11066, 0x110F0, 0x11136, 0x111D0, 0x112F0, 0x11450, 0x114D0, 0x11650,
    0x116C0, 0x11730, 0x118E0, 0x11950, 0x11C50, 0x11D50, 0x11DA0, 0x11F50, 0x16A60, 0x16AC0,
    0x16B50, 0x1D7CE, 0x1D7D8, 0x1D7E2, 0x1D7EC, 0x1D7F6, 0x1E140, 0x1E2F0, 0x1E4F0, 0x1E950,
    0x1FBF0,
];

/// The value of a Unicode decimal digit, or `None` for any other character.
pub(crate) fn decimal_digit(ch: char) -> Option<u32> {
    let code = ch as u32;
    let index = ZERO_DIGITS.partition_point(|start| *start <= code);
    let start = *ZERO_DIGITS.get(index.checked_sub(1)?)?;
    (code - start < 10).then(|| code - start)
}
