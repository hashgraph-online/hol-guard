def developer_section(segments: list[list[str]]) -> list[dict[str, object]]:
    records: list[dict[str, object]] = []
    for segment in segments:
        name, args = segment[0], segment[1:]
        records.append(
            {
                "primary": inspection._read_only_lookup_primary_segment_is_safe(name, args, home_dir=None),
                "static": inspection._static_shell_segment_is_safe(args),
                "date": inspection._read_only_lookup_date_args_are_safe(args),
                "plain": [
                    inspection._read_only_lookup_plain_targets_are_safe(args, allow_dirs=flag, home_dir=None)
                    for flag in (False, True)
                ],
                "search": [
                    inspection._read_only_lookup_search_args_are_safe(command, args, home_dir=None)
                    for command in ("grep", "egrep", "rg")
                ],
                "file_input": [
                    inspection._read_only_lookup_search_uses_file_input(command, args)
                    for command in ("grep", "egrep", "rg", "fd")
                ],
                "rg_config": inspection._ripgrep_config_is_disabled(args),
                "fd": inspection._read_only_lookup_fd_args_are_safe(args, home_dir=None),
                "fd_exec": inspection._fd_exec_sed_read_only_args_are_safe(args, home_dir=None),
                "find": inspection._read_only_lookup_find_args_are_safe(args, home_dir=None),
                "find_write": inspection._find_args_use_write_or_unsafe_exec_action(args),
                "find_sed": inspection._find_exec_sed_args_are_read_only(args),
                "find_ls": inspection._find_exec_ls_args_are_read_only(args),
            }
        )
    return records
