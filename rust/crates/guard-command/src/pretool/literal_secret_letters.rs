fn index(character: char) -> Option<usize> {
    character
        .is_ascii_lowercase()
        .then(|| usize::from(character as u8 - b'a') + 1)
}

/// Mean pair score of `token` in hundredths of a natural log. A pair that
/// holds anything other than a lowercase letter counts as never seen.
pub(super) fn english_score(token: &str) -> i32 {
    let mut previous = Some(0usize);
    let mut total = 0i32;
    let mut pairs = 0i32;
    let lowered = token.to_ascii_lowercase();
    for current in lowered.chars().map(index).chain(std::iter::once(Some(27))) {
        total += match (previous, current) {
            (Some(row), Some(column)) => i32::from(PAIRS[row][column]),
            _ => UNSEEN,
        };
        pairs += 1;
        previous = current;
    }
    total / pairs.max(1)
}
