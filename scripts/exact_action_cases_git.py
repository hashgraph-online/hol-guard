def _git_tree(extra: dict[str, Any] | None = None) -> dict[str, Any]:
    tree: dict[str, Any] = {
        "proj/.git/config": "[core]\n\trepositoryformatversion = 0\n",
        "proj/.git/HEAD": "ref: refs/heads/main\n",
        "proj/.gitattributes": "*.txt text\n",
        "proj/sub/file.txt": "x",
    }
    tree.update(extra or {})
    return tree


