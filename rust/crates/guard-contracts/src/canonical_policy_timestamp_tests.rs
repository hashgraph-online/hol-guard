use super::canonical_policy_timestamp_nanos;

#[test]
fn epoch_boundaries_and_all_nine_fractional_digits_are_exact() {
    for (text, expected) in [
        ("1970-01-01T00:00:00Z", 0),
        ("1969-12-31T23:59:59.999999999Z", -1),
        ("1970-01-01T00:00:00.000000001Z", 1),
        ("1970-01-01T00:00:00.1Z", 100_000_000),
        ("1970-01-01T00:00:00.123456789Z", 123_456_789),
        ("2000-02-29T00:00:00Z", 951_782_400_000_000_000),
        (
            "9999-12-31T23:59:59.999999999Z",
            253_402_300_799_999_999_999,
        ),
        ("0001-01-01T00:00:00Z", -62_135_596_800_000_000_000),
    ] {
        assert_eq!(
            canonical_policy_timestamp_nanos(text),
            Some(expected),
            "{text}"
        );
    }
}

#[test]
fn noncanonical_spellings_and_normalized_invalid_calendar_dates_refuse() {
    for text in [
        "0000-01-01T00:00:00Z",
        "1900-02-29T00:00:00Z",
        "2026-02-29T00:00:00Z",
        "2026-04-31T00:00:00Z",
        "2026-13-01T00:00:00Z",
        "2026-00-01T00:00:00Z",
        "2026-01-00T00:00:00Z",
        "2026-01-01T24:00:00Z",
        "2026-01-01T00:60:00Z",
        "2026-01-01T00:00:60Z",
        "2026-01-01T00:00:00.1234567890Z",
        "2026-01-01T00:00:00.Z",
        "2026-01-01T00:00:00+00:00",
        "2026-01-01T00:00:00",
        "2026-01-01T00:00Z",
        "2026-01-01 00:00:00Z",
        " 2026-01-01T00:00:00Z",
        "2026-01-01T00:00:00Z ",
        "2026-01-01t00:00:00z",
        "2026-01-01T00:00:00Zextra",
        "٢٠٢٦-01-01T00:00:00Z",
        "",
    ] {
        assert_eq!(canonical_policy_timestamp_nanos(text), None, "{text}");
    }
}
